/**
 * Skill-Based Workflow - Novel creation workflow using SkillOrchestrator
 *
 * Refactored from auto-create-workflow.ts to use the skill infrastructure:
 * - SkillOrchestrator for skill chain execution
 * - Skill loop controller for iteration decisions
 * - Reference library integration
 *
 * Pipeline: bootstrap → outline → scene-plan → write → evaluate → (revision loop)
 */

