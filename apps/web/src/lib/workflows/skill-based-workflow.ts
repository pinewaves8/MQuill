async function expandChapterToTargetSkill({
  project,
  chapter,
  chapterReport,
  wordTargetPlan,
  onChapterProgress,
  skillConfig,
}: {
  project: Project;
  chapter: { id: string; title: string };
  chapterReport: SkillWorkflowChapterReport;
  wordTargetPlan: { targetWordsPerChapter: number; minWordsPerChapter: number };
  onChapterProgress?: (message: string | null) => void;
  skillConfig: SkillConfiguration;
}): Promise<{ draftPayload: { totalWordCount: number }; warning?: string }> {
  let draftPayload = await getDraftWordCount(project.id, chapter.id);
  let attempt = 0;
  let warning: string | undefined;

  while (
    draftPayload.totalWordCount < wordTargetPlan.minWordsPerChapter &&
    attempt < 3
  ) {
    attempt += 1;
    const desiredIncrease = Math.max(
      wordTargetPlan.targetWordsPerChapter - draftPayload.totalWordCount,
      300
    );

    onChapterProgress?.(
      `《${chapter.title}》第 ${attempt} 次扩写，当前 ${draftPayload.totalWordCount}/${wordTargetPlan.minWordsPerChapter} 字`
    );

    try {
      // Use revision skill for expansion
      const segments = await draftSegmentStore.getByChapter(chapter.id);
      const sortedSegments = [...segments].sort((a, b) => a.segmentIndex - b.segmentIndex);
      const lastSegment = sortedSegments[sortedSegments.length - 1];
      const expansionContext = sortedSegments.map((s) => s.content).join('\n\n').slice(-1200);
      const revisionSkillConfig = skillConfig.skillConfigs['revision-skill'];

      await handleRevisionSkill({
        projectId: project.id,
        chapterId: chapter.id,
        segmentId: lastSegment?.id,
        originalText: expansionContext,
        suggestion: `在不改变当前剧情走向的前提下，为本章末段补写约 ${desiredIncrease} 字，增强动作、环境、心理与冲突推进，使章节更接近目标篇幅。`,
        goals: ['扩写章节篇幅', '增强场景真实感', '补足人物动作与心理'],
        constraints: [
          `保留本章既有剧情事实与人物关系`,
          `不要重复前文已经出现的段落`,
          `新增内容应自然衔接在当前末段之后`,
        ],
        applyMode: 'append',
        reference_examples: revisionSkillConfig.referenceExamples,
        technique_directives: revisionSkillConfig.techniqueDirectives,
      } as RevisionSkillInput);

      chapterReport.expansionPasses += 1;
      draftPayload = await getDraftWordCount(project.id, chapter.id);
    } catch (error) {
      warning = error instanceof Error ? error.message : String(error);
      onChapterProgress?.(`《${chapter.title}》扩写被门禁拦截：${warning}`);
      break;
    }
  }

  return { draftPayload, warning };
}

async function processIssuesForChapterSkill(
  projectId: string,
  chapter: { id: string; title: string },
  chapterReport: SkillWorkflowChapterReport,
  workflowResult: SkillWorkflowResult,
  skillConfig: SkillConfiguration
): Promise<void> {
  const issues = await getChapterIssues(projectId, chapter.id);
  chapterReport.issueCount = issues.length;
  workflowResult.results.totalIssues += issues.length;

  const actionableIssues = issues.filter((issue) => issue.status !== 'wont_fix' && issue.status !== 'fixed');

  for (const issue of actionableIssues) {
    try {
      const segments = await draftSegmentStore.getByChapter(chapter.id);
      const sortedSegments = [...segments].sort((a, b) => a.segmentIndex - b.segmentIndex);
      const lastSegment = sortedSegments[sortedSegments.length - 1];
      const revisionSkillConfig = skillConfig.skillConfigs['revision-skill'];

      await handleRevisionSkill({
        projectId,
        chapterId: chapter.id,
        segmentId: lastSegment?.id,
        originalText: issue.excerpt || '',
        suggestion: issue.suggestion || issue.title,
        goals: [],
        constraints: [],
        applyMode: 'replace',
        reference_examples: revisionSkillConfig.referenceExamples,
        technique_directives: revisionSkillConfig.techniqueDirectives,
      } as RevisionSkillInput);

      chapterReport.revisedIssues.push(issue.id);
      workflowResult.results.totalRevisedIssues += 1;
    } catch (error) {
      chapterReport.failedIssues.push({
        issueId: issue.id,
        reason: error instanceof Error ? error.message : String(error),
      });
    }
  }
}

async function getChapterIssues(projectId: string, chapterId: string): Promise<Array<{
  id: string;
  title: string;
  status: string;
  excerpt?: string;
  suggestion?: string;
}>> {
  // Import issue store dynamically to avoid circular deps
  const { issueStore } = await import('@/lib/db/projects-store');
  return issueStore.getByChapter(chapterId) as Promise<Array<{
    id: string;
    title: string;
    status: string;
    excerpt?: string;
    suggestion?: string;
  }>>;
}

async function getDraftWordCount(projectId: string, chapterId: string): Promise<{ totalWordCount: number }> {
  const segments = await draftSegmentStore.getByChapter(chapterId);
  const totalWordCount = segments.reduce((sum, seg) => sum + countWords(seg.content), 0);
  return { totalWordCount };
}

function selectOutlineVolumes(
  outline: BookOutline,
  targetChapters: number
): BookOutline['volumes'] {
  const selectedVolumes: BookOutline['volumes'] = [];
  let remaining = targetChapters;

  for (const volume of outline.volumes) {
    if (remaining <= 0) break;

    const chosenChapters = volume.chapters.slice(0, remaining);
    if (chosenChapters.length === 0) continue;

    selectedVolumes.push({
      ...volume,
      chapters: chosenChapters,
    });

    remaining -= chosenChapters.length;
  }

  if (remaining > 0) {
    console.warn(`Outline only produced ${targetChapters - remaining} chapters, not enough for workflow.`);
  }

  return selectedVolumes;
}

function getWordTargetPlan(targetLength: TargetLength, targetChapters: number): {
  targetTotalWords: number;
  minTotalWords: number;
  targetWordsPerChapter: number;
  minWordsPerChapter: number;
} {
  const targetByLength: Record<TargetLength, { target: number; min: number }> = {
    short: { target: 6000, min: 4800 },
    mid: { target: 30000, min: 24000 },
    long: { target: 80000, min: 65000 },
  };

  const plan = targetByLength[targetLength] || targetByLength.mid;
  const safeChapterCount = Math.max(targetChapters, 1);

  return {
    targetTotalWords: plan.target,
    minTotalWords: plan.min,
    targetWordsPerChapter: Math.ceil(plan.target / safeChapterCount),
    minWordsPerChapter: Math.ceil(plan.min / safeChapterCount),
  };
}

function countWords(text: string): number {
  return text.replace(/\s+/g, '').length;
}
